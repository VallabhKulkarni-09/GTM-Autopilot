import * as React from "react"
import { cn } from "@/lib/utils"

// Apple glassmorphic card — the core surface primitive.
// Translucent, blur-backed, inner-highlight border.
const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      // Glass material
      "apple-card",
      // Animation on mount
      "animate-fade-in",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

